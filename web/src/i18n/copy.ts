/**
 * `en` 声明为 `typeof zh`，少一个键就是编译错误 —— 漏译在构建时就被挡住，
 * 而不是等到界面上出现一个 undefined。
 */
export type Copy = typeof zh

const DICTIONARY: Record<Language, Copy> = { zh, en }

export function copyFor(language: Language): Copy {
  return DICTIONARY[language]
}

/** 组件取文案的唯一入口。 */
export function useCopy(): Copy {
  return copyFor(useLanguageStore((state) => state.language))
}
